        <p>Opened only by an approved monitoring rule — a subject whose OFFICIAL grade is Failing (Subject Performance Concern), or an assessment recorded as Missing (a blank saved with its assessment in the Class Record). Each subject is evaluated on its own, so a strong overall average never hides one. Any open concern makes the learner's <strong>Monitoring</strong> read For Review (none: No Current Concern). The Principal reviews it; it resolves only when the evidence changes.</p>
